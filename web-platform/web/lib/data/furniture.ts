export function furnitureCategories(): FurnitureCategory[] {
  const catMap = new Map<string, Map<string, FurnitureItem[]>>()
  for (const [cat, sub, name, modelId, price] of RAW) {
    if (!catMap.has(cat)) catMap.set(cat, new Map())
    const subMap = catMap.get(cat)!
    if (!subMap.has(sub)) subMap.set(sub, [])
    subMap.get(sub)!.push({ name, modelId, price })
  }
  return Array.from(catMap.entries()).map(([name, subMap]) => ({
    name,
    subcategories: Array.from(subMap.entries()).map(([subName, items]) => ({
      name: subName,
      items,
    })),
  }))
}
